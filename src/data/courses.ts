// Helper to get unique lecturers
export const getUniqueLecturers = (): string[] => {
  const lecturers = new Set<string>();
  courses.forEach(course => {
    course.lecturers.forEach(lecturer => {
      if (lecturer.name !== "Команда экспертов" && 
          lecturer.name !== "Специалисты Артикон" && 
          lecturer.name !== "Тренеры Артикон" &&
          lecturer.name !== "Команда экспертов Артикон" &&
          lecturer.name !== "Эксперты Артикон") {
        lecturers.add(lecturer.name);
      }
    });
  });
  return Array.from(lecturers).sort();
};
